"""Measure the light of every painted panorama offline (no GPU readback at runtime).

Writes scripts/backdrop_light_keys.gd: per environment the mean sky colour, the
colour of the land along the ground line, the colour and horizontal position of
the brightest sky light (sun, moon, lit cloud or city glow) and the source hash.
WorldLighting derives its ambient tint, rim light and ground colours from these
measured values; a world that is not listed falls back to its catalog colours.

    python3 tools/generate_backdrop_light.py          # rewrite the table
    python3 tools/generate_backdrop_light.py --check  # exit 1 when it is stale
"""
import hashlib
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "scripts/backdrop_light_keys.gd"
# Bands of the panorama height (0 top, 1 bottom = the ground line).
SKY_BAND = (0.0, 0.45)
LAND_BAND = (0.80, 0.97)
KEY_BAND = (0.0, 0.60)
# The brightest share of the key band is the light source.
KEY_SHARE = 0.06
SAMPLE_WIDTH = 418


def luminance(rgb):
    return rgb[0] * .299 + rgb[1] * .587 + rgb[2] * .114


def mean(pixels):
    count = max(1, len(pixels))
    return [sum(pixel[channel] for pixel in pixels) / count / 255.0 for channel in range(3)]


def measure(path):
    image = Image.open(path).convert("RGB")
    # A box-filtered quarter-size copy keeps the result stable and fast.
    scale = SAMPLE_WIDTH / image.width
    image = image.resize((SAMPLE_WIDTH, max(1, round(image.height * scale))), Image.BOX)
    width, height = image.size
    raw = image.tobytes()
    pixels = [tuple(raw[index:index + 3]) for index in range(0, len(raw), 3)]

    def band(rows):
        first, last = int(rows[0] * height), int(rows[1] * height)
        return [(x, y, pixels[y * width + x]) for y in range(first, last) for x in range(width)]

    sky = mean([pixel for _, _, pixel in band(SKY_BAND)])
    land = mean([pixel for _, _, pixel in band(LAND_BAND)])
    key_band = sorted(band(KEY_BAND), key=lambda entry: luminance(entry[2]), reverse=True)
    brightest = key_band[:max(1, int(len(key_band) * KEY_SHARE))]
    key = mean([pixel for _, _, pixel in brightest])
    key_x = sum(x for x, _, _ in brightest) / len(brightest) / max(1, width - 1) * 2.0 - 1.0
    return sky, land, key, key_x


def color(rgb):
    return "Color(%.3f, %.3f, %.3f)" % tuple(rgb)


def render(entries):
    lines = [
        "extends RefCounted",
        "## GENERATED by tools/generate_backdrop_light.py from the painted panoramas;",
        "## do not edit by hand. Per environment: mean sky colour, land colour along",
        "## the ground line, colour of the brightest sky light, its horizontal",
        "## position in the panorama (-1 left .. 1 right) and the source hash.",
        "const KEYS := {",
    ]
    for entry in entries:
        lines.append('\t"%s": {"sky":%s, "land":%s, "key":%s, "key_x":%.3f, "source":"%s", "sha256":"%s"},' % (
            entry["id"], color(entry["sky"]), color(entry["land"]), color(entry["key"]), entry["key_x"], entry["source"], entry["sha256"]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    catalog = json.loads((ROOT / "assets/environments/catalog.json").read_text())
    entries = []
    for environment in catalog["environments"]:
        source = ROOT / environment["path"].removeprefix("res://")
        if not source.exists():
            continue
        sky, land, key, key_x = measure(source)
        entries.append({"id": environment["id"], "sky": sky, "land": land, "key": key, "key_x": key_x,
                        "source": environment["path"], "sha256": hashlib.sha256(source.read_bytes()).hexdigest()})
    text = render(entries)
    if "--check" in sys.argv:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run tools/generate_backdrop_light.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} matches {len(entries)} panoramas")
        return 0
    OUTPUT.write_text(text)
    print(f"Measured {len(entries)} panoramas into {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
