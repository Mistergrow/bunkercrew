#!/usr/bin/env python3
"""Bake the walker cannons at every size they are drawn (style bible §1).

machine_weapons_v2.png holds the five hand-pixelled weapon families at world
size in 13 aim keys, but SiegeMachine drew them scaled by the machine's
visual scale (0.54 .. 1.28 of a world unit per texel). This tool bakes each
family at each drawn scale of the walkers that carry it (normal and elite):
the upright key (step 0, pivot on a texel corner) is reduced or enlarged
with tools/bake_infantry_world.py's palette-preserving vote (no new colour,
1-texel ink contour when reducing), then turned into the aim keys with the
RotSprite method at that density, so every key is world-texel art drawn 1:1.

    assets/enemies/machine_weapons_world.png    trimmed keys, shelf-packed
    scripts/machine_weapon_index.gd             (family, scale) -> sprites

The drawn scales come from scripts/enemy_catalog.gd (catalog scale x the
walker factor 0.75, x ELITE_SIZE_SCALE 1.10) for every walker whose weapon
is drawn from the keys. Rebuild with
    python3 tools/bake_machine_weapons_world.py [OUTPUT_DIR]
"""
from pathlib import Path
import hashlib
import json
import math
import re
import sys

import numpy as np
from PIL import Image

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT / "tools"))
import bake_infantry_world as world  # noqa: E402

SOURCE = PROJECT / "assets/enemies/machine_weapons_v2.png"
INDEX = PROJECT / "scripts/machine_weapon_index.gd"
CELL, CENTRE = 96, (48, 48)
STEPS = tuple(range(-9, 4))
PER_TURN = 48
# SiegeMachine.WEAPON_FAMILIES by chassis; GroundVariantVisual draws these
# walkers' weapons itself.
FAMILIES = {"runner": 0, "strider": 0, "breaker": 1, "colossus": 2, "assault": 3, "siege": 4}
SPECIAL = {"lancer", "sniper", "demolisher", "bastion"}
WALKER_SCALE, ELITE = 0.75, 1.10
INPUTS = ("assets/enemies/machine_weapons_v2.png", "tools/bake_machine_weapons_world.py", "tools/bake_infantry_world.py",
          "scripts/enemy_catalog.gd", "assets/workers/generate_character_workers.py")


def drawn_scales():
    """{(family, scale x 1000)} of every walker drawing its weapon from the keys."""
    text = (PROJECT / "scripts/enemy_catalog.gd").read_text()
    pairs = set()
    for kind, body in re.findall(r'"([a-z_]+)": \{"label"(.*?)\}', text):
        if kind in SPECIAL or '"human":true' in body.replace(" ", ""):
            continue
        chassis = re.search(r'"chassis":"([a-z_]+)"', body)
        chassis = chassis.group(1) if chassis else kind
        if chassis not in FAMILIES:
            continue
        scale = float(re.search(r'"scale":([0-9.]+)', body).group(1)) * WALKER_SCALE
        for factor in (1.0, ELITE):
            # As SiegeMachine.weapon_bake_key: floor(scale x 1000 + 0.5).
            pairs.add((FAMILIES[chassis], int(math.floor(scale * factor * 1000 + 0.5))))
    return sorted(pairs)


def keys(sheet, family, milli):
    scale = milli / 1000.0
    upright = np.asarray(sheet.crop((STEPS.index(0) * CELL, family * CELL, STEPS.index(0) * CELL + CELL, family * CELL + CELL)))
    size = int(math.ceil(CELL * scale)) + 6
    size += size % 2
    anchor = (size // 2, size // 2)
    reduced = world.reduce_piece(upright, CENTRE, (size, size), anchor, scale=scale)
    if scale < 1.0:
        reduced = world.contour(reduced)
    turnable = world.base.author._Turnable(Image.fromarray(reduced, "RGBA"), anchor)
    return [world._trim(np.asarray(world.base.author.turned_piece(turnable, step, PER_TURN, size, anchor)), anchor) for step in STEPS]


def main(output=None):
    out = Path(output) if output else PROJECT / "assets/enemies"
    sheet = Image.open(SOURCE).convert("RGBA")
    pairs = drawn_scales()
    sprites = []
    for family, milli in pairs:
        sprites += keys(sheet, family, milli)
    canvas, places = world.pack([image for image, _ in sprites], 512)
    target = out / "machine_weapons_world.png"
    Image.fromarray(canvas, "RGBA").save(target, optimize=True)
    values = []
    for (image, (ox, oy)), (px, py) in zip(sprites, places):
        values += [px, py, image.shape[1], image.shape[0], ox, oy]
    lines = [
        "extends RefCounted",
        "## Generated by tools/bake_machine_weapons_world.py; do not edit. Walker",
        "## cannons of machine_weapons_world.png at each drawn scale: BASES maps",
        "## \"family|scale x 1000\" to the first of its STEPS keys; DATA holds six",
        "## ints per key (atlas x, y, width, height, top-left from the pivot).",
        f"const STEPS := Vector2i({STEPS[0]},{STEPS[-1]})",
        "const BASES := {" + ", ".join(f'"{family}|{milli}": {index * len(STEPS)}' for index, (family, milli) in enumerate(pairs)) + "}",
        "const DATA: Array[int] = [",
    ]
    for start in range(0, len(values), 24):
        lines.append("\t" + ", ".join(str(v) for v in values[start:start + 24]) + ",")
    lines.append("]")
    (INDEX if output is None else out / INDEX.name).write_text("\n".join(lines) + "\n")
    notice = {
        "asset": target.name,
        "generator": "tools/bake_machine_weapons_world.py",
        "method": "The step-0 key of machine_weapons_v2.png at each drawn walker scale: palette-preserving box-filter vote "
                  "(tools/bake_infantry_world.reduce_piece), 1-texel ink contour when reduced, RotSprite aim keys at that density.",
        "license": "Original Bunkercrew project art.",
        "scales": [[family, milli / 1000.0] for family, milli in pairs], "steps": list(STEPS), "steps_per_turn": PER_TURN,
        "size": [canvas.shape[1], canvas.shape[0]],
        "source_sha256": {path: hashlib.sha256((PROJECT / path).read_bytes()).hexdigest() for path in INPUTS},
        "sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
    }
    target.with_suffix(".source.json").write_text(json.dumps(notice, indent=2) + "\n")
    print(f"BAKED MACHINE WEAPONS WORLD: {len(pairs)} scales, {len(sprites)} keys in {canvas.shape[1]}x{canvas.shape[0]}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
